#!/usr/bin/env python3
"""Generate MCU text/1-bit fault icons from the shared host error catalogue."""
import argparse
import base64
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
HOST = ROOT / 'host/klippy/extras'
MCU = ROOT / 'mcu/SOURCE_MCU/overlay/src/stm32'


def generated():
    spec = json.loads((HOST / 'm300_error_codes.json').read_text())
    bank = json.loads((HOST / 'm300_activity_sprites.json').read_text())['symbols']
    icons = list(dict.fromkeys(item['icon'] for item in spec['codes'] + spec['native']))
    lines = ['// Generated by ci/generate_error_catalog.py; do not edit.']
    for group, key in (('error_codes', 'codes'), ('error_native', 'native')):
        lines.append('static const struct m300_error_text %s[] = {' % group)
        for item in spec[key]:
            fields = [str(item.get('code', 0)), str(icons.index(item['icon']))]
            fields += [json.dumps(v) for v in (item['oled'], *item['hint'])]
            lines.append('    {' + ', '.join(fields) + '},')
        lines.append('};')
    texts = '\n'.join(lines) + '\n'
    lines = ['// Generated monochrome 50x50 fault animation frames. No framebuffer.',
             'static const uint8_t local_error_frames[%d][4][350] = {' % len(icons)]
    for name in icons:
        lines.append('  { // ' + name)
        for frame in bank[name]['frames']:
            raw = zlib.decompress(base64.b64decode(frame['zlib_b64']))
            bits = bytearray(350)
            for y in range(50):
                for x in range(50):
                    if (raw[y*25 + x//2] >> (0 if x % 2 else 4)) & 15:
                        bits[y*7 + x//8] |= 128 >> (x % 8)
            lines.append('    {')
            lines.extend('      ' + ','.join('0x%02x' % v for v in bits[i:i+20]) + ','
                         for i in range(0, len(bits), 20))
            lines.append('    },')
        lines.append('  },')
    lines.append('};')
    return {'m300_error_catalog.inc': texts, 'm300_error_icons.inc': '\n'.join(lines) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in generated().items():
        path = MCU / name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit('Outdated generated error asset: ' + name)
        else:
            path.write_text(text)
    print('PASS shared OEM error text and MCU fault animations')


if __name__ == '__main__':
    main()
