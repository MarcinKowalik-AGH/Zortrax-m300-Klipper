#!/usr/bin/env python3
"""Generate MCU text/4-bit fault icons from the shared host error catalogue."""
import argparse
import base64
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
HOST = ROOT / 'host/klippy/extras'
MCU = ROOT / 'mcu/SOURCE_MCU/overlay/src/stm32'


def generated():
    spec = json.loads((HOST / 'm300_error_codes.json').read_text())
    bank = json.loads((HOST / 'm300_activity_sprites.json').read_text())['symbols']
    icons = list(dict.fromkeys(item['icon'] for item in spec['codes'] + spec['native']))
    lines = ['// Generated by ci/generate_error_catalog.py; do not edit.']
    for group, key in (('error_codes', 'codes'), ('error_native', 'native')):
        lines.append('static const struct m300_error_text %s[] = {' % group)
        for item in spec[key]:
            fields = [str(item.get('code', 0)), str(icons.index(item['icon']))]
            fields += [json.dumps(v) for v in (item['oled'], *item['hint'])]
            lines.append('    {' + ', '.join(fields) + '},')
        lines.append('};')
    texts = '\n'.join(lines) + '\n'
    from tone_activity import indexed_rows
    raw_banks = [[zlib.decompress(base64.b64decode(frame['zlib_b64']))
                  for frame in bank[name]['frames']] for name in icons]
    pixels = indexed_rows(raw_banks, 'local_error')
    return {'m300_error_catalog.inc': texts, 'm300_error_icons.inc': pixels}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in generated().items():
        path = MCU / name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit('Outdated generated error asset: ' + name)
        else:
            path.write_text(text)
    print('PASS shared OEM error text and MCU fault animations')


if __name__ == '__main__':
    main()
